    #[test]
    fn validate_parent_child_enforces_linkage_and_sequence() {
        let parent = BlockHeader::genesis();
        let parent_hash = parent.try_hash().unwrap();
        let mut child = BlockHeader::new(parent_hash, 1);
        child.proposer = Address([2u8; 32]);
        child.set_timestamp(parent.timestamp + 2);

        child
            .validate_parent_child(&parent, child.timestamp)
            .expect("valid parent-child linkage should pass");

        // Wrong parent hash
        let mut bad_child = child.clone();
        bad_child.parent_hash = [99u8; 32];
        assert!(bad_child
            .validate_parent_child(&parent, child.timestamp)
            .is_err());

        // Wrong height
        let mut bad_height_child = child.clone();
        bad_height_child.height = 2;
        assert!(bad_height_child
            .validate_parent_child(&parent, child.timestamp)
            .is_err());

        // Regressing timestamp
        let mut bad_time_child = child.clone();
        bad_time_child.set_timestamp(parent.timestamp);
        assert!(bad_time_child
            .validate_parent_child(&parent, child.timestamp)
            .is_err());
    }
