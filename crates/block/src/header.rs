/// Canonical block header representing the consensus and state commitment for a single block.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
pub struct BlockHeader {
    /// 32-byte cryptographic hash of the immediate parent block header.
    pub parent_hash: Hash,
    /// Commitment root of the state database after applying all transactions in this block.
    pub state_root: Hash,
    /// Merkle root of all transactions contained in the block body.
    pub tx_root: Hash,
    /// Merkle root of all transaction receipts generated by executing the block body.
    pub receipts_root: Hash,
    /// Merkle root commitment to the active validator set authorized for this block.
    pub validator_root: Hash,
    /// Optional ZK-STARK / Groth16 validity proof verifying the state transition.
    pub zk_proof: Option<Vec<u8>>,
    /// Monotonically increasing height of this block in the chain.
    pub height: BlockHeight,
    /// Unix timestamp (seconds since epoch) when the block was proposed.
    pub timestamp: Timestamp,
    /// Address of the validator who proposed and signed this block.
    pub proposer: Address,
    /// Randomness beacon seed derived from VRF / threshold randomness.
    pub randomness_beacon: Hash,
    /// Block header format version for hard forks and protocol upgrades.
    #[serde(default = "default_block_version")]
    pub version: u32,
    /// Maximum gas allowed in this block. Must not exceed [`crate::MAX_BLOCK_GAS_LIMIT`].
    #[serde(default = "default_gas_limit")]
    pub gas_limit: u64,
    /// Actual gas consumed by all transactions in this block.
    #[serde(default)]
    pub gas_used: u64,
    /// Consensus-specific extra data (e.g. round metadata, proposer seal).
    /// Limited to [`crate::MAX_EXTRA_DATA_SIZE`] bytes.
    #[serde(default)]
    pub extra_data: Vec<u8>,
    /// Replay-protection chain identifier. Must match [`sxiaum_types::SXIAUM_CHAIN_ID`] on mainnet.
    #[serde(default = "default_chain_id")]
    pub chain_id: u64,
    /// Proposer's 64-byte Ed25519 signature over the canonical unsigned header hash.
    #[serde(default, with = "serde_sig")]
    pub signature: Option<[u8; 64]>,
}

fn default_block_version() -> u32 {
    crate::BLOCK_VERSION_CURRENT
}

fn default_gas_limit() -> u64 {
    crate::DEFAULT_BLOCK_GAS_LIMIT
}

fn default_chain_id() -> u64 {
    sxiaum_types::SXIAUM_CHAIN_ID
}

#[derive(Serialize)]
struct UnsignedBlockHeaderRef<'a> {
    parent_hash: Hash,
    state_root: Hash,
    tx_root: Hash,
    receipts_root: Hash,
    validator_root: Hash,
    zk_proof: Option<&'a [u8]>,
    height: BlockHeight,
    timestamp: Timestamp,
    proposer: Address,
    randomness_beacon: Hash,
    version: u32,
    gas_limit: u64,
    gas_used: u64,
    extra_data: &'a [u8],
    chain_id: u64,
    #[serde(with = "serde_sig")]
    signature: Option<[u8; 64]>,
}

impl<'a> UnsignedBlockHeaderRef<'a> {
    fn try_encode(&self) -> Result<Vec<u8>> {
        use bincode::Options;
        let options = bincode::options()
            .with_little_endian()
            .with_varint_encoding()
            .reject_trailing_bytes();

        options
            .serialize(self)
            .map_err(|e| anyhow::anyhow!("serialize unsigned header error: {}", e))
    }
}

impl BlockHeader {
    /// Create a new block header for a specific height and parent with default mainnet parameters.
    pub fn new(parent_hash: Hash, height: BlockHeight) -> Self {
        let ts = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        Self {
            parent_hash,
            state_root: [0u8; 32],
            tx_root: [0u8; 32],
            receipts_root: [0u8; 32],
            validator_root: [0u8; 32],
            zk_proof: None,
            height,
            timestamp: ts,
            proposer: Address::zero(),
            randomness_beacon: [0u8; 32],
            version: crate::BLOCK_VERSION_CURRENT,
            gas_limit: crate::DEFAULT_BLOCK_GAS_LIMIT,
            gas_used: 0,
            extra_data: Vec::new(),
            chain_id: sxiaum_types::SXIAUM_CHAIN_ID,
            signature: None,
        }
    }

    /// Create the canonical genesis block header (height 0).
    pub fn genesis() -> Self {
        Self {
            parent_hash: [0u8; 32],
            state_root: [0u8; 32],
            tx_root: [0u8; 32],
            receipts_root: [0u8; 32],
            validator_root: [0u8; 32],
            zk_proof: None,
            height: 0,
            timestamp: crate::GENESIS_TIMESTAMP,
            proposer: Address::zero(),
            randomness_beacon: [0u8; 32],
            version: crate::BLOCK_VERSION_CURRENT,
            gas_limit: crate::DEFAULT_BLOCK_GAS_LIMIT,
            gas_used: 0,
            extra_data: Vec::new(),
            chain_id: sxiaum_types::SXIAUM_CHAIN_ID,
            signature: None,
        }
    }

    /// Calculate the canonical 32-byte SHA-256 hash of the header.
    ///
    /// The hash is computed deterministically over the header fields with `signature`
    /// set to `None`, ensuring signatures sign the exact preimage and remain verifiable.
    pub fn try_hash(&self) -> Result<Hash> {
        let unsigned_view = UnsignedBlockHeaderRef {
            parent_hash: self.parent_hash,
            state_root: self.state_root,
            tx_root: self.tx_root,
            receipts_root: self.receipts_root,
            validator_root: self.validator_root,
            zk_proof: self.zk_proof.as_deref(),
            height: self.height,
            timestamp: self.timestamp,
            proposer: self.proposer,
            randomness_beacon: self.randomness_beacon,
            version: self.version,
            gas_limit: self.gas_limit,
            gas_used: self.gas_used,
            extra_data: self.extra_data.as_slice(),
            chain_id: self.chain_id,
            signature: None,
        };
        let bytes = unsigned_view.try_encode()?;
        let mut hasher = Sha256::new();
        hasher.update(&bytes);
        let result = hasher.finalize();
        let mut out = [0u8; 32];
        out.copy_from_slice(&result);
        Ok(out)
    }

    #[cfg(test)]
    pub fn hash(&self) -> Hash {
        self.try_hash().expect("header hashing should not fail")
    }

    /// Serialize the header into its canonical deterministic binary format.
    pub fn try_encode(&self) -> Result<Vec<u8>> {
        <Self as Canonical>::try_encode(self)
    }

    /// Deserialize a header from its canonical binary format.
    pub fn decode(bytes: &[u8]) -> Result<Self> {
        <Self as Canonical>::decode(bytes)
    }

    /// Return the canonical binary size of the header in bytes.
    pub fn size_bytes(&self) -> Result<usize> {
        self.try_encode().map(|b| b.len())
    }

    /// Verify that the header correctly links to its expected parent hash.
    #[must_use]
    pub fn verify_parent(&self, expected_parent_hash: Hash) -> bool {
        self.parent_hash == expected_parent_hash
    }

    /// Verify that the block height strictly matches the expected height.
    #[must_use]
    pub fn verify_height(&self, expected_height: BlockHeight) -> bool {
        self.height == expected_height
    }

    /// Verify that the timestamp is strictly greater than the previous block's timestamp.
    #[must_use]
    pub fn verify_timestamp(&self, previous_timestamp: Timestamp) -> bool {
        self.timestamp > previous_timestamp
    }

    /// Sign the block header as the proposer using an Ed25519 signing key.
    ///
    /// Automatically populates the header's `proposer` address if it is currently zero.
    pub fn sign(&mut self, signing_key: &SigningKey) -> Result<()> {
        let derived_proposer = Address::from_public_key(&signing_key.verifying_key().to_bytes());
        if self.proposer.is_zero() {
            self.proposer = derived_proposer;
        } else if self.proposer != derived_proposer {
            return Err(HeaderError::ProposerKeyMismatch {
                expected: self.proposer,
                derived: derived_proposer,
            }
            .into());
        }

        let hash = self.try_hash()?;
        let sig = signing_key.sign(&hash);
        self.signature = Some(sig.to_bytes());
        Ok(())
    }

    /// Sign the block header using an abstract signer (in-memory or remote HSM).
    ///
    /// Automatically populates the header's `proposer` address if currently zero.
    pub fn sign_with_signer<S: sxiaum_crypto::Signer + ?Sized>(
        &mut self,
        signer: &S,
    ) -> Result<()> {
        let pubkey = signer.public_key();
        let derived_proposer = Address::from_public_key(&pubkey.to_bytes());
        if self.proposer.is_zero() {
            self.proposer = derived_proposer;
        } else if self.proposer != derived_proposer {
            return Err(HeaderError::ProposerKeyMismatch {
                expected: self.proposer,
                derived: derived_proposer,
            }
            .into());
        }

        let hash = self.try_hash()?;
        let sig = signer.sign(&hash)?;
        self.signature = Some(sig.to_bytes());
        Ok(())
    }

    /// Verify the proposer's Ed25519 signature on the header with strict malleability checks.
    pub fn verify_signature(&self, public_key_bytes: &[u8; 32]) -> Result<bool> {
        let sig_bytes = self
            .signature
            .ok_or_else(|| HeaderError::MissingSignature)?;

        let derived_proposer = Address::from_public_key(public_key_bytes);
        if derived_proposer != self.proposer {
            return Err(HeaderError::ProposerKeyMismatch {
                expected: self.proposer,
                derived: derived_proposer,
            }
            .into());
        }

        let public_key = VerifyingKey::from_bytes(public_key_bytes)
            .map_err(|e| HeaderError::InvalidPublicKey(e.to_string()))?;

        let sig = Signature::from_bytes(&sig_bytes);

        public_key
            .verify_strict(&self.try_hash()?, &sig)
            .map(|_| true)
            .map_err(|e| HeaderError::SignatureVerificationFailed(format!("{:?}", e)).into())
    }

    // --- Field Setters ---

    pub fn set_state_root(&mut self, root: Hash) {
        self.state_root = root;
    }

    pub fn set_tx_root(&mut self, root: Hash) {
        self.tx_root = root;
    }

    pub fn set_receipts_root(&mut self, root: Hash) {
        self.receipts_root = root;
    }

    pub fn set_validator_root(&mut self, root: Hash) {
        self.validator_root = root;
    }

    pub fn set_randomness_beacon(&mut self, beacon: Hash) {
        self.randomness_beacon = beacon;
    }

    pub fn set_zk_proof(&mut self, proof: Vec<u8>) {
        self.zk_proof = Some(proof);
    }

    pub fn set_timestamp(&mut self, ts: Timestamp) {
        self.timestamp = ts;
    }

    pub fn set_proposer(&mut self, proposer: Address) {
        self.proposer = proposer;
    }

    pub fn set_version(&mut self, version: u32) {
        self.version = version;
    }

    pub fn set_gas_limit(&mut self, gas_limit: u64) {
        self.gas_limit = gas_limit;
    }

    pub fn set_gas_used(&mut self, gas_used: u64) {
        self.gas_used = gas_used;
    }

    pub fn set_extra_data(&mut self, data: Vec<u8>) {
        self.extra_data = data;
    }

    pub fn set_chain_id(&mut self, chain_id: u64) {
        self.chain_id = chain_id;
    }

    // --- Validation Methods ---

    /// Perform basic structural and size checks on the header fields.
    pub fn validate_basic(&self) -> Result<()> {
        if self.timestamp == 0 {
            return Err(HeaderError::ZeroTimestamp.into());
        }

        if self.height == 0 && self.parent_hash != [0u8; 32] {
            return Err(HeaderError::GenesisParentNonZero.into());
        }

        if self.extra_data.len() > crate::MAX_EXTRA_DATA_SIZE {
            return Err(HeaderError::ExtraDataTooLarge {
                size: self.extra_data.len(),
                max: crate::MAX_EXTRA_DATA_SIZE,
            }
            .into());
        }

        if let Some(proof) = &self.zk_proof {
            if proof.len() > crate::MAX_ZK_PROOF_SIZE {
                return Err(HeaderError::ZkProofTooLarge {
                    size: proof.len(),
                    max: crate::MAX_ZK_PROOF_SIZE,
                }
                .into());
            }
        }

        Ok(())
    }

    /// Perform comprehensive mainnet validation on the header.
    ///
    /// Validates:
    /// * Basic structural limits
    /// * Canonical protocol version
    /// * Replay protection chain identifier
    /// * Gas limit bounded between [`crate::MIN_BLOCK_GAS_LIMIT`] and [`crate::MAX_BLOCK_GAS_LIMIT`]
    /// * Gas used does not exceed gas limit
    /// * Non-genesis blocks require non-zero proposer
    /// * Timestamp does not drift beyond [`crate::MAX_FUTURE_BLOCK_TIME_SECS`]
    /// * Timestamp is at or after [`crate::GENESIS_TIMESTAMP`]
    pub fn validate_mainnet(&self, local_time: Timestamp) -> Result<()> {
        self.validate_basic()?;

        if self.version != crate::BLOCK_VERSION_CURRENT {
            return Err(HeaderError::InvalidVersion {
                expected: crate::BLOCK_VERSION_CURRENT,
                actual: self.version,
            }
            .into());
        }

        if self.chain_id != sxiaum_types::SXIAUM_CHAIN_ID {
            return Err(HeaderError::InvalidChainId {
                expected: sxiaum_types::SXIAUM_CHAIN_ID,
                actual: self.chain_id,
            }
            .into());
        }

        if self.gas_limit > crate::MAX_BLOCK_GAS_LIMIT {
            return Err(HeaderError::GasLimitExceeded {
                gas_limit: self.gas_limit,
                max: crate::MAX_BLOCK_GAS_LIMIT,
            }
            .into());
        }

        if self.gas_limit < crate::MIN_BLOCK_GAS_LIMIT {
            return Err(HeaderError::GasLimitTooLow {
                gas_limit: self.gas_limit,
                min: crate::MIN_BLOCK_GAS_LIMIT,
            }
            .into());
        }

        if self.gas_used > self.gas_limit {
            return Err(HeaderError::GasUsedExceedsLimit {
                gas_used: self.gas_used,
                gas_limit: self.gas_limit,
            }
            .into());
        }

        if self.height > 0 {
            if self.parent_hash == [0u8; 32] {
                return Err(HeaderError::NonGenesisParentZero {
                    height: self.height,
                }
                .into());
            }
            if self.proposer.is_zero() {
                return Err(HeaderError::NonGenesisZeroProposer.into());
            }
        } else if !self.proposer.is_zero() {
            return Err(HeaderError::GenesisNonZeroProposer.into());
        }

        if self.timestamp < crate::GENESIS_TIMESTAMP {
            return Err(HeaderError::TimestampBeforeGenesis {
                timestamp: self.timestamp,
                genesis_time: crate::GENESIS_TIMESTAMP,
            }
            .into());
        }

        let max_allowed_time = local_time.saturating_add(crate::MAX_FUTURE_BLOCK_TIME_SECS);
        if self.timestamp > max_allowed_time {
            return Err(HeaderError::FutureTimestamp {
                timestamp: self.timestamp,
                local_time,
                max_drift: crate::MAX_FUTURE_BLOCK_TIME_SECS,
            }
            .into());
        }

        Ok(())
    }

    /// Perform pairwise validation between a child header and its verified parent header.
    pub fn validate_parent_child(&self, parent: &BlockHeader, local_time: Timestamp) -> Result<()> {
        self.validate_mainnet(local_time)?;

        let parent_hash = parent.try_hash()?;
        if !self.verify_parent(parent_hash) {
            return Err(HeaderError::ParentHashMismatch {
                expected: hex::encode(parent_hash),
                actual: hex::encode(self.parent_hash),
            }
            .into());
        }

        let expected_height = parent
            .height
            .checked_add(1)
            .ok_or(HeaderError::HeightOverflow {
                height: parent.height,
            })?;

        if !self.verify_height(expected_height) {
            return Err(HeaderError::HeightMismatch {
                expected: expected_height,
                actual: self.height,
            }
            .into());
        }

        if self.timestamp <= parent.timestamp {
            return Err(HeaderError::TimestampRegression {
                child_time: self.timestamp,
                parent_time: parent.timestamp,
            }
            .into());
        }

        Ok(())
    }
}

impl sxiaum_crypto::hash::Hashable for BlockHeader {
    fn try_hash(&self) -> Result<sxiaum_crypto::hash::Hash, anyhow::Error> {
        self.try_hash()
    }
}

